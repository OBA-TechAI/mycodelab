    def append_results(model_name, y_pred, y_prob, start_time, best_params,
                       model=None, dl_model=False, input=None):
        nonlocal results
        def inference():
          if input is not None:
            return model.predict(input)
          return model.predict(X_test_dl if dl_model else X_test)

        mem_usage = memory_usage(inference)
        mem_in_B = (max(mem_usage) - min(mem_usage)) * (1024 ** 2)

        def count_params(model, X_train=None):
            import numpy as np

            try:
                if hasattr(model, 'count_params'):
                    return model.count_params()

                elif hasattr(model, 'coef_'):
                    return model.coef_.size + (1 if getattr(model, 'fit_intercept', False) else 0)

                elif hasattr(model, 'theta_') and hasattr(model, 'var_'):
                    n_classes, n_features = model.theta_.shape
                    return 2 * n_classes * n_features + n_classes

                elif hasattr(model, 'estimators_') and hasattr(model.estimators_[0], 'tree_'):
                    return sum(est.tree_.node_count for est in model.estimators_)

                elif hasattr(model, '_fit_X'):
                    return model._fit_X.size

                elif hasattr(model, 'support_vectors_'):
                    return model.support_vectors_.size
                elif 'xgb' in str(type(model)).lower():
                    booster = model.get_booster()
                    # Return total number of nodes as param count
                    total_nodes = sum(
                        booster.trees_to_dataframe()[booster.trees_to_dataframe()['Tree'] == i].shape[0]
                        for i in range(booster.num_boosted_rounds())
                    )
                    return total_nodes
                elif hasattr(model, 'tree_'):
                    return model.tree_.node_count


                else:
                    return "N/A"

            except Exception as e:
                return "N/A"


